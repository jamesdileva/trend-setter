"""Local API for the desktop shell and supervisor (architecture.md §15).

Rules encoded here:

- Loopback only: middleware rejects any non-loopback client as defense in
  depth on top of the loopback-only bind in ``main.py``. The API must never
  be reachable from the LAN.
- Read models and narrowly scoped commands only: there is no
  order-submission endpoint. Only the engine execution path can trade,
  after risk approval.
- The per-session token gates endpoints beyond basic health. The token is
  generated by the supervisor per launch and passed via the environment —
  never on the command line (implementation.md §12).

Coinbase endpoints handle credentials without ever exposing them: the
private key arrives once, goes straight into the OS secret store, and every
response carries only non-secret status metadata.
"""

from __future__ import annotations

import secrets as pysecrets
from datetime import UTC, datetime

import httpx
from fastapi import Depends, FastAPI, Header, HTTPException, Request
from fastapi.responses import JSONResponse, Response
from sqlalchemy import select
from starlette.middleware.base import RequestResponseEndpoint

from trendbot import __version__
from trendbot.api.schemas import CredentialRequest
from trendbot.application.coinbase_connection import (
    CoinbaseConnectionService,
    default_client_factory,
)
from trendbot.application.state import EngineRuntime
from trendbot.database.models import EngineEvent
from trendbot.database.session import Database
from trendbot.security.secret_store import SecretStore

LOOPBACK_HOSTS = frozenset({"127.0.0.1", "::1"})
TOKEN_HEADER = "X-Local-Token"
DIAGNOSTICS_EVENT_LIMIT = 20


def _iso(value: datetime | None) -> str | None:
    return None if value is None else value.strftime("%Y-%m-%dT%H:%M:%SZ")


def _utc_now_iso() -> str:
    return datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def create_app(
    local_token: str | None,
    *,
    database: Database,
    secret_store: SecretStore,
    coinbase_transport: httpx.BaseTransport | None = None,
) -> FastAPI:
    """Build the engine app with explicit wiring.

    ``local_token`` is the per-session token generated by the supervisor.
    When it is absent (a manual bare start), token-gated endpoints report
    themselves unavailable instead of silently serving without auth.
    """
    runtime = EngineRuntime()
    connection_service = CoinbaseConnectionService(
        database=database,
        secret_store=secret_store,
        client_factory=default_client_factory(coinbase_transport),
    )
    app = FastAPI(
        title="trendbot engine",
        version=__version__,
        docs_url=None,
        redoc_url=None,
        openapi_url=None,
    )

    @app.middleware("http")
    async def reject_non_loopback(
        request: Request, call_next: RequestResponseEndpoint
    ) -> Response:
        host = request.client.host if request.client else ""
        if host not in LOOPBACK_HOSTS:
            return JSONResponse(
                status_code=403,
                content={"detail": "The engine API is only available on this computer."},
            )
        return await call_next(request)

    def require_local_token(
        x_local_token: str | None = Header(default=None, alias=TOKEN_HEADER),
    ) -> None:
        if local_token is None:
            raise HTTPException(
                status_code=503,
                detail=(
                    "Engine commands are unavailable: the engine was started "
                    "without a session token."
                ),
            )
        if x_local_token is None or not pysecrets.compare_digest(x_local_token, local_token):
            raise HTTPException(
                status_code=401,
                detail="This action requires the local session token.",
            )

    @app.get("/health")
    def health() -> dict[str, str]:
        """Liveness probe used by the supervisor. No token required."""
        return {
            "status": "ok",
            "engine_version": __version__,
            "utc_time": _utc_now_iso(),
        }

    @app.get("/status", dependencies=[Depends(require_local_token)])
    def status() -> JSONResponse:
        """Lifecycle snapshot for the UI. Requires the session token."""
        return JSONResponse(
            status_code=200,
            content={
                "mode": "paper",
                "state": runtime.state.value,
                "engine_version": __version__,
                "started_at": _iso(runtime.started_at),
                "uptime_seconds": runtime.uptime_seconds(),
            },
        )

    @app.post("/coinbase/credentials", dependencies=[Depends(require_local_token)])
    def connect_coinbase(payload: CredentialRequest) -> JSONResponse:
        """Validate and store a Coinbase credential (wizard Save & test)."""
        result = connection_service.connect(payload.key_name, payload.private_key_pem)
        if result.ok:
            return JSONResponse(
                status_code=200,
                content={
                    "status": "valid",
                    "permissions": result.permissions,
                    "trade_permission": result.trade_access,
                },
            )
        return JSONResponse(
            status_code=400,
            content={"status": result.error_kind, "message": result.message},
        )

    @app.get("/coinbase/connection", dependencies=[Depends(require_local_token)])
    def connection_status() -> dict[str, object]:
        """Non-secret connection summary for the wizard."""
        state = connection_service.status()
        return {
            "connected": state.connected,
            "key_reference": state.key_reference,
            "permissions": state.permissions,
            "last_validated_at": state.last_validated_at,
        }

    @app.post("/coinbase/test-connection", dependencies=[Depends(require_local_token)])
    def test_coinbase_connection() -> JSONResponse:
        """Re-validate the stored credential against Coinbase."""
        result = connection_service.retest()
        if result.ok:
            return JSONResponse(
                status_code=200,
                content={
                    "status": "valid",
                    "permissions": result.permissions,
                    "trade_permission": result.trade_access,
                },
            )
        status_code = 400 if result.error_kind != "not_connected" else 409
        return JSONResponse(
            status_code=status_code,
            content={"status": result.error_kind, "message": result.message},
        )

    @app.post("/coinbase/disconnect", dependencies=[Depends(require_local_token)])
    def disconnect_coinbase() -> dict[str, bool]:
        """Remove the stored secret and credential reference."""
        return {"disconnected": connection_service.disconnect()}

    @app.get("/diagnostics", dependencies=[Depends(require_local_token)])
    def diagnostics() -> dict[str, object]:
        """A redacted support snapshot. Never includes secret material."""
        state = connection_service.status()
        with database.session() as session:
            events = session.scalars(
                select(EngineEvent)
                .order_by(EngineEvent.created_at.desc(), EngineEvent.id.desc())
                .limit(DIAGNOSTICS_EVENT_LIMIT)
            ).all()
        return {
            "engine_version": __version__,
            "utc_time": _utc_now_iso(),
            "connection": {
                "connected": state.connected,
                "permissions": state.permissions,
                "last_validated_at": state.last_validated_at,
            },
            "database": {"file_name": database.path.name},
            "recent_events": [
                {
                    "event_type": event.event_type,
                    "component": event.component,
                    "created_at": _iso(event.created_at),
                }
                for event in events
            ],
        }

    return app
