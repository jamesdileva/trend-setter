LOOPBACK_HOSTS = frozenset({"127.0.0.1", "::1"})
PAPER_WARNING_TEXT = (
    "PAPER TRADING — simulated funds only. No real orders are placed and "
    "no real balances are shown."
)
TOKEN_HEADER = "X-Local-Token"
DIAGNOSTICS_EVENT_LIMIT = 20


def _iso(value: datetime | None) -> str | None:
    return None if value is None else value.strftime("%Y-%m-%dT%H:%M:%SZ")


def _utc_now_iso() -> str:
    return datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def create_app(
    local_token: str | None,
    *,
    database: Database,
    secret_store: SecretStore,
    coinbase_transport: httpx.BaseTransport | None = None,
    feed_factory: Callable[[], Any] | None = None,
    market_status_provider: Callable[[], dict[str, object]] | None = None,
) -> FastAPI:
    """Build the engine app with explicit wiring.

    ``local_token`` is the per-session token generated by the supervisor.
    When it is absent (a manual bare start), token-gated endpoints report
    themselves unavailable instead of silently serving without auth.

    ``feed_factory`` (when provided) starts the live market-data feed as a
    background task for the app's lifetime; ``market_status_provider``
    supplies its status snapshot for the local API and the UI.
    """
    runtime = EngineRuntime()
    paper_account = PaperAccount(database)
    trading_controller = TradingController(database)
    connection_service = CoinbaseConnectionService(
        database=database,
        secret_store=secret_store,
        client_factory=default_client_factory(coinbase_transport),
    )
    strategy_engine = StrategyEngine(database)
    live_arming = LiveArmingController(database)

    @asynccontextmanager
    async def lifespan(_app: FastAPI) -> AsyncIterator[None]:
        feed_task: asyncio.Task[None] | None = None
        if feed_factory is not None:
            feed = feed_factory()
            feed_task = asyncio.create_task(feed.run())
        try:
            yield
        finally:
            if feed_task is not None:
                feed_task.cancel()
                try:
                    await feed_task
                except asyncio.CancelledError:
                    pass

    app = FastAPI(
        title="trendbot engine",
        version=__version__,
        docs_url=None,
        redoc_url=None,
        openapi_url=None,
        lifespan=lifespan,
    )

    @app.middleware("http")
    async def reject_non_loopback(
        request: Request, call_next: RequestResponseEndpoint
    ) -> Response:
        host = request.client.host if request.client else ""
        if host not in LOOPBACK_HOSTS:
            return JSONResponse(
                status_code=403,
                content={"detail": "The engine API is only available on this computer."},
            )
        return await call_next(request)

    def require_local_token(
        x_local_token: str | None = Header(default=None, alias=TOKEN_HEADER),
    ) -> None:
        if local_token is None:
            raise HTTPException(
                status_code=503,
                detail=(
                    "Engine commands are unavailable: the engine was started "
                    "without a session token."
                ),
            )
        if x_local_token is None or not pysecrets.compare_digest(x_local_token, local_token):
            raise HTTPException(
                status_code=401,
                detail="This action requires the local session token.",
            )

    @app.get("/health")
    def health() -> dict[str, str]:
        """Liveness probe used by the supervisor. No token required."""
        return {
            "status": "ok",
            "engine_version": __version__,
            "utc_time": _utc_now_iso(),
        }

    @app.get("/status", dependencies=[Depends(require_local_token)])
    def status() -> JSONResponse:
        """Lifecycle snapshot for the UI. Requires the session token."""
        return JSONResponse(
            status_code=200,
            content={
                "mode": "paper",
                "state": runtime.state.value,
                "engine_version": __version__,
                "started_at": _iso(runtime.started_at),
                "uptime_seconds": runtime.uptime_seconds(),
            },
        )

    @app.post("/coinbase/credentials", dependencies=[Depends(require_local_token)])
    def connect_coinbase(payload: CredentialRequest) -> JSONResponse:
        """Validate and store a Coinbase credential (wizard Save & test)."""
        result = connection_service.connect(payload.key_name, payload.private_key_pem)
        if result.ok:
            return JSONResponse(
                status_code=200,
                content={
                    "status": "valid",
                    "permissions": result.permissions,
                    "trade_permission": result.trade_access,
                },
            )
        return JSONResponse(
            status_code=400,
            content={"status": result.error_kind, "message": result.message},
        )

    @app.get("/coinbase/connection", dependencies=[Depends(require_local_token)])
    def connection_status() -> dict[str, object]:
        """Non-secret connection summary for the wizard."""
        state = connection_service.status()
        return {
            "connected": state.connected,
            "key_reference": state.key_reference,
            "permissions": state.permissions,
            "last_validated_at": state.last_validated_at,
        }

    @app.post("/coinbase/test-connection", dependencies=[Depends(require_local_token)])
    def test_coinbase_connection() -> JSONResponse:
        """Re-validate the stored credential against Coinbase."""
        result = connection_service.retest()
        if result.ok:
            return JSONResponse(
                status_code=200,
                content={
                    "status": "valid",
                    "permissions": result.permissions,
                    "trade_permission": result.trade_access,
                },
            )
        status_code = 400 if result.error_kind != "not_connected" else 409
        return JSONResponse(
            status_code=status_code,
            content={"status": result.error_kind, "message": result.message},
        )

    @app.post("/coinbase/disconnect", dependencies=[Depends(require_local_token)])
    def disconnect_coinbase() -> dict[str, bool]:
        """Remove the stored secret and credential reference."""
        return {"disconnected": connection_service.disconnect()}

    @app.get("/diagnostics", dependencies=[Depends(require_local_token)])
    def diagnostics() -> dict[str, object]:
        """A redacted support snapshot. Never includes secret material."""
        state = connection_service.status()
        with database.session() as session:
            events = session.scalars(
                select(EngineEvent)
                .order_by(EngineEvent.created_at.desc(), EngineEvent.id.desc())
                .limit(DIAGNOSTICS_EVENT_LIMIT)
            ).all()
        return {
            "engine_version": __version__,
            "utc_time": _utc_now_iso(),
            "connection": {
                "connected": state.connected,
                "permissions": state.permissions,
                "last_validated_at": state.last_validated_at,
            },
            "database": {"file_name": database.path.name},
            "recent_events": [
                {
                    "event_type": event.event_type,
                    "component": event.component,
                    "created_at": _iso(event.created_at),
                }
                for event in events
            ],
        }

    @app.post("/paper/start", dependencies=[Depends(require_local_token)])
    def paper_start() -> dict[str, object]:
        """Start (or resume) the paper session. Simulated funds only."""
        paper_account.ensure_session()
        trading_controller.set_mode(TradingMode.NORMAL, reason="paper start")
        return {"status": "running", "warning": PAPER_WARNING_TEXT}

    @app.post("/paper/pause", dependencies=[Depends(require_local_token)])
    def paper_pause() -> dict[str, object]:
        """Pause new entries; existing management continues."""
        trading_controller.set_mode(TradingMode.ENTRIES_PAUSED, reason="paper pause")
        return {"status": "entries_paused", "warning": PAPER_WARNING_TEXT}

    @app.post("/paper/stop", dependencies=[Depends(require_local_token)])
    def paper_stop() -> dict[str, object]:
        """Stop trading: entries paused and open orders canceled by the controller."""
        trading_controller.set_mode(TradingMode.STOPPED, reason="paper stop")
        return {"status": "stopped", "warning": PAPER_WARNING_TEXT}

    @app.post("/paper/emergency-stop", dependencies=[Depends(require_local_token)])
    def paper_emergency_stop() -> dict[str, object]:
        """Kill switch: blocks everything until explicitly re-armed."""
        trading_controller.set_mode(TradingMode.EMERGENCY_STOPPED, reason="paper emergency stop")
        return {"status": "emergency_stopped", "warning": PAPER_WARNING_TEXT}

    @app.post("/paper/reset", dependencies=[Depends(require_local_token)])
    def paper_reset(payload: PaperResetRequest) -> JSONResponse:
        """Wipe simulated balances/history. Requires confirm=true."""
        try:
            paper_account.reset(confirm=payload.confirm)
        except ResetNotConfirmedError as exc:
            return JSONResponse(
                status_code=400,
                content={"status": "reset_not_confirmed", "message": str(exc)},
            )
        return JSONResponse(
            status_code=200,
            content={"status": "reset", "warning": PAPER_WARNING_TEXT},
        )

    @app.get("/paper/status", dependencies=[Depends(require_local_token)])
    def paper_status() -> dict[str, object]:
        """Paper account, position, and mode — always labeled as simulated."""
        mode = trading_controller.current_mode()
        position = PositionRepository(database).get("BTC-USD")
        cash = paper_account.cash()
        size = (position.size if position else Decimal(0)) or Decimal(0)
        return {
            "warning": PAPER_WARNING_TEXT,
            "account_kind": "paper",
            "mode": mode.value,
            "entries_allowed": trading_controller.entries_allowed(),
            "cash": str(cash),
            "starting_balance": str(paper_account.starting_balance()),
            "session_started_at": paper_account.session_started_at(),
            "position": {
                "product_id": "BTC-USD",
                "size": str(size or Decimal(0)),
                "side": (position.side if position and size else "flat"),
                "average_entry_price": (
                    str(position.average_entry_price)
                    if position and position.average_entry_price
                    else None
                ),
            },
            "recent_snapshots": [
                {
                    "available": str(row.available),
                    "captured_at": _iso(row.captured_at),
                }
                for row in paper_account.snapshots(limit=10)
            ],
        }

    @app.get("/market-data/status", dependencies=[Depends(require_local_token)])
    def market_data_status() -> dict[str, object]:
        """Live feed health for the UI: state, last message, last complete candle."""
        if market_status_provider is None:
            return {"running": False, "state": "not_wired"}
        return {"running": True, **market_status_provider()}

    @app.post("/strategy/config", dependencies=[Depends(require_local_token)])
    def save_strategy_config(payload: StrategyConfigRequest) -> JSONResponse:
        """Validate and store a new active strategy config version."""
        try:
            result = strategy_engine.set_config(
                product_id=payload.product_id,
                timeframe=payload.timeframe,
                fast_ema_period=payload.fast_ema_period,
                slow_ema_period=payload.slow_ema_period,
                rsi_period=payload.rsi_period,
                rsi_entry_ceiling=payload.rsi_entry_ceiling,
                rsi_exit_floor=payload.rsi_exit_floor,
            )
        except Exception as exc:  # noqa: BLE001 - plain-language validation errors
            return JSONResponse(
                status_code=400,
                content={"status": "invalid_config", "message": str(exc)},
            )
        return JSONResponse(status_code=200, content=result)

    @app.get("/strategy/current", dependencies=[Depends(require_local_token)])
    def current_strategy() -> dict[str, object]:
        """The active strategy configuration, or not-configured status."""
        config = strategy_engine.current_config()
        if config is None:
            return {"configured": False}
        return {
            "configured": True,
            "config": {
                "product_id": config.product_id,
                "timeframe": config.timeframe,
                "fast_ema_period": config.fast_ema_period,
                "slow_ema_period": config.slow_ema_period,
                "rsi_period": config.rsi_period,
                "rsi_entry_ceiling": config.rsi_entry_ceiling,
                "rsi_exit_floor": config.rsi_exit_floor,
                "config_hash": config.config_hash(),
            },
            "recent_signals": strategy_engine.recent_signals(config.product_id, config.timeframe),
        }

    @app.post("/strategy/evaluate", dependencies=[Depends(require_local_token)])
    def evaluate_strategy(payload: StrategyEvaluateRequest) -> JSONResponse:
        """Evaluate the active strategy over stored candles (evidence only)."""
        try:
            decision = strategy_engine.evaluate(payload.product_id, payload.timeframe)
        except StrategyNotConfiguredError as exc:
            return JSONResponse(
                status_code=409,
                content={"status": "not_configured", "message": str(exc)},
            )
        return JSONResponse(
            status_code=200,
            content={
                "signal": decision.signal.value,
                "product_id": decision.product_id,
                "timeframe": decision.timeframe,
                "candle_time": _iso(decision.candle_time),
                "reason_code": decision.reason_code,
                "explanation": decision.explanation,
                "indicator_values": decision.indicator_values,
                "strategy_name": decision.strategy_name,
                "strategy_version": decision.strategy_version,
                "config_hash": decision.config_hash,
            },
        )

    @app.post("/backtest/run", dependencies=[Depends(require_local_token)])
    def run_backtest(payload: BacktestRunRequest) -> JSONResponse:
        """Run and persist a labeled historical simulation over stored candles."""
        try:
            start = datetime.fromisoformat(payload.start) if payload.start else None
            end = datetime.fromisoformat(payload.end) if payload.end else None
            config = EmaRsiConfig(
                product_id=payload.product_id,
                timeframe=payload.timeframe,
                fast_ema_period=payload.fast_ema_period,
                slow_ema_period=payload.slow_ema_period,
                rsi_period=payload.rsi_period,
                rsi_entry_ceiling=payload.rsi_entry_ceiling,
                rsi_exit_floor=payload.rsi_exit_floor,
            )
            result = run_backtest_over_store(
                database,
                product_id=payload.product_id,
                timeframe=payload.timeframe,
                start=start,
                end=end,
                config=config,
                assumptions=FeeAssumptions(
                    fee_bps=payload.fee_bps,
                    slippage_bps=payload.slippage_bps,
                ),
                initial_quote=Decimal(str(payload.initial_quote)),
                position_size_quote=Decimal(str(payload.position_size_quote)),
                in_sample_fraction=payload.in_sample_fraction,
            )
        except InsufficientDataError as exc:
            return JSONResponse(
                status_code=409,
                content={"status": "insufficient_data", "message": str(exc)},
            )
        except Exception as exc:  # noqa: BLE001 - plain-language validation errors
            return JSONResponse(
                status_code=400,
                content={"status": "invalid_request", "message": str(exc)},
            )
        return JSONResponse(status_code=200, content=result)

    @app.get("/backtest/runs", dependencies=[Depends(require_local_token)])
    def list_backtest_runs() -> dict[str, object]:
        """Recent simulation runs (labeled; summaries only)."""
        repo = BacktestRepository(database)
        runs = []
        for row in repo.list_runs():
            runs.append(
                {
                    "run_id": row.id,
                    "product_id": row.product_id,
                    "timeframe": row.granularity,
                    "start": _iso(row.start_time),
                    "end": _iso(row.end_time),
                    "metrics": row.metrics,
                }
            )
        return {
            "warning": "HISTORICAL SIMULATIONS — estimates, not guarantees.",
            "runs": runs,
        }

    @app.get("/live/status", dependencies=[Depends(require_local_token)])
    def live_status() -> dict[str, object]:
        """Live-arming state and prerequisite summary."""
        armed = live_arming.is_armed()
        return {
            "armed": armed,
            "warning": (
                "LIVE TRADING ARMED — real funds."
                if armed
                else "Live trading is disarmed. Paper mode is the default."
            ),
        }

    @app.post("/live/arm-request", dependencies=[Depends(require_local_token)])
    def live_arm_request() -> JSONResponse:
        """Step 1: check prerequisites and issue a one-time arm token."""
        # Credential/trade-permission state comes from the connection service.
        state = connection_service.status()
        creds_ok = state.connected
        trade_ok = state.permissions == "view+trade" if state.connected else False
        result = live_arming.request_arm(
            credentials_valid=creds_ok,
            trade_permission=trade_ok,
            fresh_market_data=True,
            risk_limits_acknowledged=True,
        )
        status_code = 200 if result.requested else 400
        return JSONResponse(
            status_code=status_code,
            content={
                "requested": result.requested,
                "token": result.token,
                "message": result.message,
            },
        )

    @app.post("/live/arm-confirm", dependencies=[Depends(require_local_token)])
    def live_arm_confirm(payload: dict[str, object]) -> JSONResponse:
        """Step 2: present the token to arm live trading."""
        token = str(payload.get("token", ""))
        result = live_arming.confirm_arm(token)
        status_code = 200 if result.requested else 400
        return JSONResponse(
            status_code=status_code,
            content={"armed": result.requested, "message": result.message},
        )

    @app.post("/live/disarm", dependencies=[Depends(require_local_token)])
    def live_disarm() -> dict[str, object]:
        """Disarm live trading (open orders and positions are not touched)."""
        live_arming.disarm(reason="manual disarm via API")
        return {"armed": False, "message": "Live trading is disarmed."}

    @app.get("/candles", dependencies=[Depends(require_local_token)])
    def candles(
        product_id: str = "BTC-USD",
        timeframe: str = "5m",
        limit: int = 200,
    ) -> dict[str, object]:
        """Stored candles with EMA overlays for the chart."""
        granularity = granularity_for_timeframe(timeframe)

        seconds = granularity_seconds(granularity)
        latest = CandleRepository(database).latest_complete_start(product_id, granularity)
        if latest is None:
            return {"candles": [], "fast_ema": [], "slow_ema": [], "rsi": []}

        required = max(51, limit)
        window_start = latest - timedelta(seconds=(required - 1) * seconds)
        stored = CandleRepository(database).get_range(
            product_id, granularity, window_start, latest + timedelta(seconds=1)
        )
        closes = [candle.close for candle in stored]
        fast_series = ema(closes, 20)
        slow_series = ema(closes, 50)
        rsi_series = rsi(closes, 14)

        candles_out = []
        fast_out = []
        slow_out = []
        rsi_out = []
        for index, candle in enumerate(stored):
            time_iso = candle.start_time.strftime("%Y-%m-%dT%H:%M:%SZ")
            candles_out.append({
                "time": time_iso,
                "open": str(candle.open),
                "high": str(candle.high),
                "low": str(candle.low),
                "close": str(candle.close),
            })
            if fast_series[index] is not None:
                fast_out.append({"time": time_iso, "value": f"{fast_series[index]:.2f}"})
            if slow_series[index] is not None:
                slow_out.append({"time": time_iso, "value": f"{slow_series[index]:.2f}"})
            if rsi_series[index] is not None:
                rsi_out.append({"time": time_iso, "value": f"{rsi_series[index]:.2f}"})

        latest_price = str(stored[-1].close) if stored else None
        latest_time = _iso(stored[-1].start_time) if stored else None
        return {
            "candles": candles_out,
            "fast_ema": fast_out,
            "slow_ema": slow_out,
            "rsi": rsi_out,
            "latest_price": latest_price,
            "latest_time": latest_time,
        }

    return app
