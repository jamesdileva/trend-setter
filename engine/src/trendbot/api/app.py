"""Local API for the desktop shell and supervisor (architecture.md §15).

Rules encoded here:

- Loopback only: middleware rejects any non-loopback client as defense in
  depth on top of the loopback-only bind in ``main.py``. The API must never
  be reachable from the LAN.
- Read models only: there is no order-submission endpoint.
- The per-session token gates endpoints beyond basic health. The token is
  generated by the supervisor per launch and passed via the environment —
  never on the command line (implementation.md §12).
"""

from __future__ import annotations

import secrets
from datetime import UTC, datetime

from fastapi import FastAPI, Header, Request
from fastapi.responses import JSONResponse, Response
from starlette.middleware.base import RequestResponseEndpoint

from trendbot import __version__
from trendbot.application.state import EngineRuntime

LOOPBACK_HOSTS = frozenset({"127.0.0.1", "::1"})
TOKEN_HEADER = "X-Local-Token"


def create_app(local_token: str | None = None) -> FastAPI:
    """Build the engine app.

    ``local_token`` is the per-session token generated by the supervisor.
    When it is absent (a manual bare start), token-gated endpoints report
    themselves unavailable instead of silently serving without auth.
    """
    runtime = EngineRuntime()
    app = FastAPI(
        title="trendbot engine",
        version=__version__,
        docs_url=None,
        redoc_url=None,
        openapi_url=None,
    )

    @app.middleware("http")
    async def reject_non_loopback(
        request: Request, call_next: RequestResponseEndpoint
    ) -> Response:
        host = request.client.host if request.client else ""
        if host not in LOOPBACK_HOSTS:
            return JSONResponse(
                status_code=403,
                content={"detail": "The engine API is only available on this computer."},
            )
        return await call_next(request)

    @app.get("/health")
    def health() -> dict[str, str]:
        """Liveness probe used by the supervisor. No token required."""
        return {
            "status": "ok",
            "engine_version": __version__,
            "utc_time": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        }

    @app.get("/status")
    def status(
        x_local_token: str | None = Header(default=None, alias=TOKEN_HEADER),
    ) -> JSONResponse:
        """Lifecycle snapshot for the UI. Requires the session token."""
        if local_token is None:
            detail = "Engine status is unavailable: the engine was started without a session token."
            return JSONResponse(status_code=503, content={"detail": detail})
        if x_local_token is None or not secrets.compare_digest(x_local_token, local_token):
            return JSONResponse(
                status_code=401,
                content={"detail": "Engine status requires the local session token."},
            )
        return JSONResponse(
            status_code=200,
            content={
                "mode": "paper",
                "state": runtime.state.value,
                "engine_version": __version__,
                "started_at": runtime.started_at.strftime("%Y-%m-%dT%H:%M:%SZ"),
                "uptime_seconds": runtime.uptime_seconds(),
            },
        )

    return app
